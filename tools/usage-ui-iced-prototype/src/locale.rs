pub fn default_language() -> Language {
    if std::env::var("USAGE_UI_LANGUAGE")
        .is_ok_and(|value| matches!(value.to_ascii_lowercase().as_str(), "ar" | "arabic"))
    {
        Language::Arabic
    } else {
        Language::English
    }
}

